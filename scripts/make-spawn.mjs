#!/usr/bin/env node

// One command from an interview brief to a finished server spawn:
//
//   node scripts/make-spawn.mjs brief.json
//   node scripts/make-spawn.mjs --brief '{"name":"CheeseSMP","type":"normal","npcs":8,"theme":"autumn"}'
//
// Writes into the out dir (default minecraft-builds/<slug>/):
//   <slug>.recipe.mjs        the editable recipe (brief + an after() hook for hand additions)
//   <slug>.nbt / .schem / .litematic   the build (paste with WorldEdit / Litematica / structure block)
//   <slug>.placements.json   every NPC, hologram, crate, portal and region with world coordinates
//   <slug>.setup.md          the plugin commands (Citizens, DecentHolograms, crates, WorldGuard)
//   renders/*.png            an overview and a close view of the plaza (isorender, CPU only)
// Brief fields: references/spawns/README.md §1 and assets/spawn-briefs/*.json.

import { spawnSync } from 'node:child_process'
import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'
import { resolveBrief } from './lib/spawngen/index.mjs'

const here = path.dirname(fileURLToPath(import.meta.url))
const root = path.resolve(here, '..')

function usage() {
  return `Usage:
  node scripts/make-spawn.mjs <brief.json> [options]
  node scripts/make-spawn.mjs --brief '<json>' [options]

Options:
  --out-dir <dir>   where to write (default minecraft-builds/<slug>)
  --recipe <file>   rebuild from an edited <slug>.recipe.mjs instead of a brief
  --no-render       skip the renders            --no-convert   skip .schem/.litematic
  --no-spawn-view   skip the eye-level view (the only render that needs Playwright)
  --seed <n>        another variation of the same brief (overrides the brief's seed)
  --quiet           only the final report
`
}

const argv = process.argv.slice(2)
const flag = name => argv.includes(name)
const opt = name => {
  const i = argv.indexOf(name)
  return i >= 0 ? argv[i + 1] : undefined
}
if (!argv.length || flag('-h') || flag('--help')) {
  console.log(usage())
  process.exit(argv.length ? 0 : 1)
}
const quiet = flag('--quiet')
const log = (...a) => { if (!quiet) console.log(...a) }

// ---------------------------------------------------------------- the brief and the recipe
let recipePath = opt('--recipe')
let brief
if (recipePath) {
  recipePath = path.resolve(recipePath)
  const mod = await import(`file://${recipePath}`)
  brief = resolveBrief(mod.brief ?? {}).brief
} else {
  const inline = opt('--brief')
  const file = argv.find((a, i) => !a.startsWith('--') && !['--brief', '--out-dir', '--seed', '--recipe'].includes(argv[i - 1]))
  if (!inline && !file) {
    console.error('make-spawn: give a brief file or --brief \'{...}\'')
    process.exit(1)
  }
  let raw
  try {
    raw = JSON.parse(inline ?? fs.readFileSync(file, 'utf8'))
  } catch (err) {
    console.error(`make-spawn: the brief is not valid JSON (${err.message})`)
    process.exit(1)
  }
  if (opt('--seed')) raw.seed = Number(opt('--seed'))
  const norm = resolveBrief(raw)
  brief = norm.brief
  for (const w of norm.warnings) console.log(`brief: ${w}`)
}
const outDir = path.resolve(opt('--out-dir') ?? path.join(root, 'minecraft-builds', brief.slug))
fs.mkdirSync(outDir, { recursive: true })
if (!recipePath) {
  recipePath = path.join(outDir, `${brief.slug}.recipe.mjs`)
  let lib = path.relative(outDir, path.join(root, 'scripts/lib/spawngen/index.mjs')).split(path.sep).join('/')
  if (!lib.startsWith('.')) lib = `./${lib}`
  const json = JSON.stringify(brief, null, 2)
  fs.writeFileSync(recipePath, `// ${brief.name}: generated by scripts/make-spawn.mjs. Rebuild after an edit with
//   node scripts/make-spawn.mjs --recipe ${path.relative(root, recipePath).split(path.sep).join('/')}
// Change the brief below (size, npcs, theme, seed...) or add hand-made details in after(ctx):
//   ctx.b (the builder: set, box, tree, sign...), ctx.kit, ctx.FY (plaza floor level),
//   ctx.C ([x, z] of the spawn), ctx.layout (every slot: hero, crates, rtp, pvp, houses, npcRing).

import { generateSpawn } from '${lib}'

export const brief = ${json}

export default api => generateSpawn(api, brief, {
  after(ctx) {
    // e.g. ctx.b.tree([ctx.C[0] + 20, ctx.FY + 1, ctx.C[1] - 30], 'cherry', { seed: 3 })
  },
})
`)
}
const slug = brief.slug

// ---------------------------------------------------------------- build
const node = process.execPath
const stderrLines = []
const run = (args, label) => {
  const r = spawnSync(node, args, { cwd: root, encoding: 'utf8', maxBuffer: 1 << 28 })
  if (r.stderr) stderrLines.push(...r.stderr.split('\n').filter(Boolean))
  if (r.status !== 0) {
    console.error(`make-spawn: ${label} failed\n${(r.stderr || r.error?.message || '').slice(-4000)}`)
    process.exit(1)
  }
  return r.stdout
}
log(`building ${brief.name} (${brief.type}, ${brief.size}x${brief.size}, ${brief.npcs.length} NPCs, theme ${brief.theme})...`)
const t0 = Date.now()
const out = run([path.join(here, 'run-build.mjs'), recipePath, '--out-dir', outDir, '--name', slug, '--origin', brief.origin.join(','), '--world', brief.world, '--json'], 'build')
let summary = {}
try {
  summary = JSON.parse(out.slice(out.indexOf('{')))
} catch {
  summary = {}
}
const nbt = path.join(outDir, `${slug}.nbt`)
if (!fs.existsSync(nbt)) {
  console.error(`make-spawn: the build wrote no ${slug}.nbt\n${out.slice(-2000)}`)
  process.exit(1)
}
log(`  built in ${((Date.now() - t0) / 1000).toFixed(1)}s`)

// ---------------------------------------------------------------- convert
const files = [nbt]
if (!flag('--no-convert')) {
  for (const ext of ['schem', 'litematic']) {
    const target = path.join(outDir, `${slug}.${ext}`)
    run([path.join(here, 'convert.mjs'), nbt, '--out', target, '--name', brief.name], `convert to .${ext}`)
    files.push(target)
  }
}

// ---------------------------------------------------------------- renders
const renders = []
if (!flag('--no-render')) {
  const rdir = path.join(outDir, 'renders')
  fs.mkdirSync(rdir, { recursive: true })
  const S = brief.size
  const meta = readJson(path.join(outDir, `${slug}.placements.json`))
  const spawnRec = meta?.placements?.find(p => p.type === 'spawn')
  const floor = spawnRec ? spawnRec.pos[1] : null
  const px = String(S > 200 ? 2 : S > 130 ? 3 : 4)
  const views = [
    { name: 'overview-se', args: ['--from', 'se', '--px', px] },
    { name: 'overview-nw', args: ['--from', 'nw', '--px', px] },
  ]
  // the plaza close-up: the middle of the canvas seen from behind the spawn (south-east), like a player
  const r = Math.round(S * (brief.type === 'plus' ? 0.24 : 0.3))
  const c = Math.floor(S / 2)
  views.push({ name: 'plaza', args: ['--from', 'se', '--px', S > 200 ? '5' : '7', '--box', [c - r, c - r, c + r, c + r].join(','), ...(floor ? ['--ymin', String(floor - 4)] : [])] })
  for (const v of views) {
    const file = path.join(rdir, `${slug}-${v.name}.png`)
    run([path.join(here, 'isorender.mjs'), nbt, '--out', file, ...v.args], `render ${v.name}`)
    renders.push(file)
  }
  // what a player sees on joining: eye level at the spawn, looking north (needs render.mjs's
  // Playwright + Chromium; skipped quietly without them)
  if (floor !== null && !flag('--no-spawn-view')) {
    const H = brief.height ?? 90
    const clip = [c - 70, Math.max(0, floor - 3), c - Math.min(90, c - 1), c + 70, H - 1, c + 4].map(v => Math.max(0, v))
    const r2 = spawnSync(node, [path.join(here, 'render.mjs'), '--nbt', nbt, '--out', rdir, '--yaw', '0', '--pitch', '2', '--target', `${c},${floor + 3},${c - 20}`, '--distance', '22', '--fov', '72', '--view-name', `${slug}-spawn-view`, '--clip', clip.join(','), '--no-sheet', '--width', '1280', '--height', '720'], { cwd: root, encoding: 'utf8', maxBuffer: 1 << 26, timeout: 240000 })
    const file = path.join(rdir, `${slug}-spawn-view.png`)
    if (r2.status === 0 && fs.existsSync(file)) renders.push(file)
    else log('  (spawn-view render skipped: scripts/render.mjs needs Playwright + Chromium, see SKILL.md Setup)')
  }
}

// ---------------------------------------------------------------- report
const placements = readJson(path.join(outDir, `${slug}.placements.json`))
const rel = f => path.relative(process.cwd(), f)
console.log(`\n${brief.name}: done`)
console.log(`  recipe     ${rel(recipePath)}`)
for (const f of files) console.log(`  build      ${rel(f)}`)
for (const f of [`${slug}.placements.json`, `${slug}.setup.md`]) if (fs.existsSync(path.join(outDir, f))) console.log(`  setup      ${rel(path.join(outDir, f))}`)
for (const f of renders) console.log(`  render     ${rel(f)}`)
if (summary.blockCount) console.log(`  blocks     ${summary.blockCount.toLocaleString('en-US')}`)
const list = placements?.placements ?? []
const spawn = list.find(p => p.type === 'spawn')
if (spawn) console.log(`  spawn      ${spawn.world.pos.join(' ')} in ${brief.world} (paste the minimum corner at ${brief.origin.join(' ')})`)
const npcs = list.filter(p => p.type === 'npc' && p.role !== 'statue')
if (npcs.length) console.log(`  npcs       ${npcs.length}: ${npcs.map(n => n.label).join(', ')}`)
const problems = summary.builder?.problems ?? []
const warnings = [...problems.map(p => `invalid block: ${typeof p === 'string' ? p : JSON.stringify(p)}`), ...stderrLines.filter(l => /^builder: /.test(l)).map(l => l.replace(/^builder: /, ''))]
if (warnings.length) {
  console.log(`  warnings   ${warnings.length}`)
  for (const w of warnings.slice(0, 15)) console.log(`    - ${w}`)
  if (warnings.length > 15) console.log(`    ... ${warnings.length - 15} more`)
}
console.log(`\nNext: look at every render; fix what looks wrong in the brief or after(ctx), then
  node scripts/make-spawn.mjs --recipe ${rel(recipePath)}`)

function readJson(file) {
  try {
    return JSON.parse(fs.readFileSync(file, 'utf8'))
  } catch {
    return null
  }
}
